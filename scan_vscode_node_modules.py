#!/usr/bin/env python3
import os
import sys
import json
import csv
import tempfile
import subprocess
import shutil

# --- CONFIG -----------------------------------------------------------------

DEFAULT_ROOTS = [
    {
        "label": "VSCode App",
        "path": "/Applications/Visual Studio Code.app/Contents/Resources/app",
    },
    {
        "label": "VSCode Insiders App",
        "path": "/Applications/Visual Studio Code - Insiders.app/Contents/Resources/app",
    },
    {
        "label": "VSCode User Extensions",
        "path": os.path.expanduser("~/.vscode/extensions"),
    },
    {
        "label": "VSCode Insiders User Extensions",
        "path": os.path.expanduser("~/.vscode-insiders/extensions"),
    },
]

# ---------------------------------------------------------------------------

def find_node_modules_dirs(root_path):
    """Yield all node_modules directories under root_path."""
    for dirpath, dirnames, filenames in os.walk(root_path):
        # speed: skip hidden dirs
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        if os.path.basename(dirpath) == "node_modules":
            yield dirpath


def iter_packages_in_node_modules(node_modules_path):
    """
    Yield (package_name, package_dir) for every package in a node_modules dir.
    Handles:
      - node_modules/foo
      - node_modules/@scope/bar
    """
    try:
        entries = os.listdir(node_modules_path)
    except OSError:
        return

    for entry in entries:
        full = os.path.join(node_modules_path, entry)
        if not os.path.isdir(full):
            continue

        # Scoped packages like @types/...
        if entry.startswith("@"):
            try:
                scoped_entries = os.listdir(full)
            except OSError:
                continue
            for child in scoped_entries:
                child_full = os.path.join(full, child)
                if not os.path.isdir(child_full):
                    continue
                pkg_name = f"{entry}/{child}"  # @scope/name
                yield pkg_name, child_full
        else:
            yield entry, full


def read_package_json(pkg_dir):
    """Return (name, version, package_json_path) from package.json if present."""
    pkg_json_path = os.path.join(pkg_dir, "package.json")
    if not os.path.isfile(pkg_json_path):
        return None, None, None

    try:
        with open(pkg_json_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        name = data.get("name")
        version = data.get("version")
        return name, version, pkg_json_path
    except Exception:
        return None, None, pkg_json_path


def detect_source_label_for_node_modules(node_modules_path, root_label, root_path):
    """Label for normal node_modules directories."""
    try:
        rel = os.path.relpath(node_modules_path, root_path)
    except ValueError:
        return root_label

    parts = rel.split(os.sep)
    # For ~/.vscode/extensions/<ext>/node_modules
    if "Extensions" in root_label and len(parts) >= 2:
        ext_folder = parts[0]
        return f"{root_label} (extension: {ext_folder})"
    return root_label


def scan_root_node_modules(root_label, root_path, writer):
    """Scan all filesystem node_modules under one root."""
    if not os.path.isdir(root_path):
        return

    for nm_dir in find_node_modules_dirs(root_path):
        source_label = detect_source_label_for_node_modules(nm_dir, root_label, root_path)
        for pkg_name, pkg_dir in iter_packages_in_node_modules(nm_dir):
            name, version, pkg_json_path = read_package_json(pkg_dir)
            effective_name = name or pkg_name
            effective_version = version or ""
            writer.writerow(
                {
                    "name": effective_name,
                    "version": effective_version,
                    "source": source_label,
                    "package_json_path": pkg_json_path or "",
                }
            )


# ------------------------ ASAR HANDLING -------------------------------------

def has_npx():
    return shutil.which("npx") is not None


def list_asar_files(root_path):
    """Yield all .asar files under root_path."""
    for dirpath, dirnames, filenames in os.walk(root_path):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for fn in filenames:
            if fn.endswith(".asar"):
                yield os.path.join(dirpath, fn)


def asar_list(asar_path):
    """Return stripped paths inside an asar archive using `npx asar list`."""
    try:
        result = subprocess.run(
            ["npx", "--yes", "asar", "list", asar_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True,
        )
        paths = []
        for line in result.stdout.splitlines():
            line = line.strip()
            if not line:
                continue
            # strip any leading slash so extract-file works
            paths.append(line.lstrip("/"))
        return paths
    except Exception as e:
        print(f"[ASAR] ERROR listing {asar_path}: {e}", file=sys.stderr)
        return []


def asar_extract_file(asar_path, inner_path, work_dir):
    """
    Extract a single file from an asar archive into work_dir.

    Returns the full path to the extracted file, or None on failure.
    """
    try:
        # electron asar CLI writes to CWD with the internal file name
        subprocess.run(
            ["npx", "--yes", "asar", "extract-file", asar_path, inner_path],
            cwd=work_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True,
        )
        dest_path = os.path.join(work_dir, os.path.basename(inner_path))
        if not os.path.isfile(dest_path):
            print(
                f"[ASAR] Extract reported success but {dest_path} not found "
                f"({asar_path}::{inner_path})",
                file=sys.stderr,
            )
            return None
        return dest_path
    except Exception as e:
        print(f"[ASAR] ERROR extracting {inner_path} from {asar_path}: {e}", file=sys.stderr)
        return None


def scan_root_asars(root_label, root_path, writer):
    """Scan all .asar archives for package.json files."""
    if not os.path.isdir(root_path):
        return

    if not has_npx():
        print(f"[ASAR] SKIP {root_label}: npx not found", file=sys.stderr)
        return

    for asar_path in list_asar_files(root_path):
        rel_asar = os.path.relpath(asar_path, root_path)
        source_prefix = f"{root_label} (asar: {rel_asar})"

        inner_paths = asar_list(asar_path)
        pkg_json_paths = [p for p in inner_paths if p.endswith("package.json")]
        print(f"[ASAR] {asar_path}: found {len(pkg_json_paths)} package.json files", file=sys.stderr)

        for pkg_inner in pkg_json_paths:
            pkg_inner_clean = pkg_inner.lstrip("/")

            # create a temp dir for this one file
            tmp_dir = tempfile.mkdtemp(prefix="asar_pkg_")
            try:
                extracted_path = asar_extract_file(asar_path, pkg_inner_clean, tmp_dir)
                if not extracted_path:
                    continue

                try:
                    with open(extracted_path, "r", encoding="utf-8") as f:
                        data = json.load(f)
                except Exception as e:
                    print(
                        f"[ASAR] JSON parse failure: {asar_path}::{pkg_inner_clean} → {e}",
                        file=sys.stderr,
                    )
                    continue

                name = data.get("name") or os.path.basename(os.path.dirname(pkg_inner_clean))
                version = data.get("version") or ""

                writer.writerow({
                    "name": name,
                    "version": version,
                    "source": source_prefix,
                    "package_json_path": f"{asar_path}::{pkg_inner_clean}",
                })
            finally:
                shutil.rmtree(tmp_dir, ignore_errors=True)

        print(f"[ASAR] {source_prefix} complete.", file=sys.stderr)

# ------------------------------ MAIN ----------------------------------------

def main():
    fieldnames = ["name", "version", "source", "package_json_path"]
    writer = csv.DictWriter(sys.stdout, fieldnames=fieldnames)
    writer.writeheader()

    for root in DEFAULT_ROOTS:
        label = root["label"]
        path = root["path"]

        # 1) Normal node_modules
        scan_root_node_modules(label, path, writer)

        # 2) ASAR contents (only meaningful for app roots, but harmless for others)
        scan_root_asars(label, path, writer)


if __name__ == "__main__":
    main()
